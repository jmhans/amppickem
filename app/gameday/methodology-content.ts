  "## Step 1 — Scoring rate via credibility weighting",
  "",
  "Each team's projected scoring rate is a straight Bühlmann-style credibility estimate between",
  "its own season-to-date average and the league mean:",
  "",
  "```",
  "Z_i  = n_i / (n_i + k)",
  "λ̂_i = [ Z_i · X̄_i + (1 − Z_i) · μ ] / 60",
  "```",
  "",
  "`Z_i` is the credibility factor: a team with zero games logged this season gets `Z_i = 0`",
  "(100% league average); by `n_i = k = 4` games, its own sample carries half the weight; well",
  "beyond that, `λ̂_i` is mostly the team's own number. This is exactly the standard",
  "credibility-weighted-average construction — `k` is the \"how many games until I trust your own",
  "data\" knob, chosen at 4 somewhat arbitrarily and not (yet) fit to anything.",
  "",
