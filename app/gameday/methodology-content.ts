  "",
  "## Notation",
  "",
  "| Symbol | Meaning |",
  "| --- | --- |",
  "| `t` | Elapsed game time (minutes) |",
  "| `τ` | Minutes remaining in regulation, `τ = 60 − t` (undefined in overtime — see below) |",
  "| `S_H(t)`, `S_A(t)` | Current home / away score |",
  "| `n_i` | Games team *i* has played this season with a final score on record |",
  "| `X̄_i` | Team *i*'s season-to-date average points per game |",
  "| `μ` | League-wide average points per game, pooled across every final game logged this season (falls back to a fixed 22.5 if literally none exist yet, e.g. Week 1 pregame) |",
  "| `k` | Credibility parameter, currently **4** (games) |",
  "| `λ̂_i` | Team *i*'s blended projected scoring rate, points/minute |",
  "| `σ` | Full-game (60-minute) single-team scoring standard deviation, currently a fixed **10** |",
