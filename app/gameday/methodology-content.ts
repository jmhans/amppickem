  "## Step 1 — Scoring rate via credibility weighting",
  "",
  "Each team's projected scoring rate is a straight Bühlmann-style credibility estimate between",
  "its own season-to-date average and the league mean:",
  "",
  "```",
  "Z_i  = n_i / (n_i + k)",
  "λ̂_i = [ Z_i · X̄_i + (1 − Z_i) · μ ] / 60",
  "```",
  "",
  "`Z_i` is the credibility factor: a team with zero games logged this season gets `Z_i = 0`",
  "(100% league average); by `n_i = k = 4` games, its own sample carries half the weight; well",
  "beyond that, `λ̂_i` is mostly the team's own number. This is exactly the standard",
  "credibility-weighted-average construction — `k` is the \"how many games until I trust your own",
  "data\" knob, chosen at 4 somewhat arbitrarily and not (yet) fit to anything.",
  "",
  "**Deliberately not included in `λ̂_i`: today's own in-game pace.** An earlier version of this",
  "discussion considered blending in the current game's actual scoring rate, weighted by elapsed",
  "time. We dropped it — a team that's run unusually hot or cold *so far today* tends to see that",
  "invert going forward (garbage-time scoring once a game is out of reach; a leading team killing",
  "clock and running more), so extrapolating today's pace forward would systematically mislead",
  "rather than help. `λ̂_i` is fixed once computed and does not update from the live game.",
  "",
  "## Step 2 — Distribution of remaining points",
  "",
  "Treating scoring as accruing at an approximately constant rate with roughly homogeneous,",
  "independent increments over disjoint time intervals — the same structural assumption behind",
  "modeling aggregate claims over sub-periods of an exposure period — remaining points for each",
  "team is approximately normal by a CLT-style argument:",
  "",
  "```",
  "R_i ~ N( λ̂_i · τ,  σ² · τ / 60 )",
  "```",
  "",
  "The mean scales linearly in `τ` (constant rate). The **variance also scales linearly in",
  "`τ`** under the same independent-increments assumption — identical to how variance",
  "accumulates linearly under Brownian motion, or how aggregate-loss variance scales with",
  "exposure time under a compound process with constant intensity. `σ` itself is a single fixed",
  "constant (10), not team-specific, not weather- or pace-adjusted, not yet fit to this league's",
  "own data — see limitations.",
  "",
  "**Pregame does NOT use this distribution at all.** An earlier version ran the same",
  "`R_i ~ N(λ̂_i·τ, σ²·τ/60)` machinery pregame too, with `τ = 60` and `S_H(t) = S_A(t) = 0`. A",
  "live check against real market odds (see Validation) showed that overconfident — with only",
  "a couple games of season data, `λ̂_i` leans heavily on the league average, which doesn't",
  "reflect the specific matchup, and that bias compounds for totals (both teams' pace errors",
  "add) rather than canceling (as they mostly do for a margin). Pregame now uses the market's",
  "own live price instead — see the **Pregame** section after Step 4. Steps 1-4 below describe",
  "the in-game model only; they start being used once there's an actual score to project from.",
  "",
  "## Step 3 — Projected final margin / total",
  "",
  "Let `Ŝ_H = S_H(t) + R_H` and `Ŝ_A = S_A(t) + R_A` be the projected final scores. Assuming",
  "`R_H ⟂ R_A` (independence — see limitations), and since a linear combination of independent",
  "normals is itself normal:",
  "",
  "**Margin** (for spread picks), `M = Ŝ_H − Ŝ_A`:",
  "",
  "```",
  "M ~ N( μ_M, σ_M² ),  where",
  "μ_M  = [S_H(t) − S_A(t)] + (λ̂_H − λ̂_A) · τ",
  "σ_M² = Var(R_H) + Var(R_A) = σ² · τ / 30",
  "```",
  "",
  "**Total** (for over/under picks), `T = Ŝ_H + Ŝ_A`, has the *same* variance as `M` —",
