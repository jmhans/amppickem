  "## Step 2 — Distribution of remaining points",
  "",
  "Treating scoring as accruing at an approximately constant rate with roughly homogeneous,",
  "independent increments over disjoint time intervals — the same structural assumption behind",
  "modeling aggregate claims over sub-periods of an exposure period — remaining points for each",
  "team is approximately normal by a CLT-style argument:",
  "",
  "```",
  "R_i ~ N( λ̂_i · τ,  σ² · τ / 60 )",
  "```",
  "",
  "The mean scales linearly in `τ` (constant rate). The **variance also scales linearly in",
  "`τ`** under the same independent-increments assumption — identical to how variance",
  "accumulates linearly under Brownian motion, or how aggregate-loss variance scales with",
  "exposure time under a compound process with constant intensity. `σ` itself is a single fixed",
  "constant (10), not team-specific, not weather- or pace-adjusted, not yet fit to this league's",
