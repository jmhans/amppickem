  "With `Φ` the standard normal CDF (own Abramowitz–Stegun `erf` approximation, no external",
  "library):",
  "",
  "For a **spread** pick, home covers a line `s` (home's own line, sportsbook sign convention —",
  "negative means home favored) iff `M > −s`:",
  "",
  "```",
  "Pr(home covers) = Φ( (μ_M + s) / σ_M )",
  "Pr(away covers) = 1 − Pr(home covers)",
  "```",
  "",
  "For a **total** pick against line `L`:",
  "",
  "```",
  "Pr(over)  = Φ( (μ_T − L) / σ_T )",
  "Pr(under) = 1 − Pr(over)",
  "```",
  "",
  "Whichever side matches the participant's actual pick is what the dashboard displays.",
  "",
  "## Pregame — re-anchoring the market's live price",
  "",
  "Pregame there's no score to project from, and — per the Validation finding above — no good",
  "reason to trust our own team-pace projection over the market's. But the pool's own locked",
  "line `L` (frozen at whatever it was when it locked, typically Tuesday) can drift from where",
